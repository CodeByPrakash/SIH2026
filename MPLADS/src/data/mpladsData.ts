export function getAlertsForRole(role?: UserRole, user?: User): Alert[] {
  if (!role || role === "Citizen") return [];

  return ALERTS.filter((alert) => {
    if (alert.roles && alert.roles.includes(role)) {
      return true;
    }
    if (role === "Ministry") return !alert.district;
    if (role === "MP") return user?.constituency && alert.district === user.constituency;
    if (role === "State") return user?.state && alert.state === user.state;
    if (role === "District") return user?.district && alert.district === user.district;
    return false;
  });
}


